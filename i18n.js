  function evTranslate(msg) {
    if (lang === 'tr' || !msg || typeof msg !== 'string') return msg;
    let out = msg;
    for (const [re, rep] of EV_PATTERNS) {
      const m = out.match(re);
      if (m) {
        out = typeof rep === 'function' ? out.replace(re, () => rep(m)) : out.replace(re, rep);
        break;
      }
    }
    if (!NAME_MAP) buildNameMap();
    for (const [tr, en] of NAME_MAP) out = out.split(tr).join(en);
    return out;
  }

